# === Stage 35: Добавь рекомендации следующего действия на основе текущего состояния ===
# Project: ResearchCatalog
def suggest_next_action(state):
    """
    На основе текущего состояния проекта предлагает следующее действие.
    state — словарь с ключами:
      - current_file: путь к текущему файлу
      - last_commit: последняя закоммиченная строка (хэш или описание)
      - total_lines: общее количество строк в файле
      - features_completed: список завершённых фичей
      - features_planned: список планируемых фичей
    Возвращает: словарь с ключами:
      - action: описание следующего шага
      - priority: "high" | "medium" | "low"
      - reason: почему выбрано это действие
    """
    completed = set(state.get("features_completed", []))
    planned = state.get("features_planned", [])
    total = state.get("total_lines", 0)

    # Если файл уже содержит >100 строк — предложим разбить на модули
    if total > 100:
        return {
            "action": "Разбить monolithic файл на модули (models, views, utils)",
            "priority": "high",
            "reason": "Файл стал слишком большим для дальнейшего ручного редактирования"
        }

    # Если есть незавершённые фичи — предложить продолжить
    if planned:
        next_feature = planned[0]
        if next_feature not in completed:
            return {
                "action": f"Реализовать фичу: {next_feature}",
                "priority": "high",
                "reason": "Существует запланированная фича, не реализованная в коде"
            }

    # Если все фичи завершены — предложить добавить тесты или документацию
    if total > 20:
        return {
            "action": "Написать модульные тесты для основных функций",
            "priority": "medium",
            "reason": "Проект функционален, но ему нужны тесты для надёжности"
        }

    # Если файл пуст или почти пуст — предложить создать базовую структуру
    if total < 5:
        return {
            "action": "Создать базовую структуру проекта (imports, функции, типы)",
            "priority": "high",
            "reason": "Файл практически пуст, нужно начать с фундамента"
        }

    # По умолчанию — предложить рефакторинг или добавление нового фича
    return {
        "action": "Добавить новую фичу или улучшить существующую",
        "priority": "low",
        "reason": "Проект стабилен, можно расширять функциональность"
    }
